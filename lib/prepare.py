"""Prepare a day folder: tags.json (skeleton if missing), parsed lyrics, cover art.
usage: prepare.py DAY_DIR WORK_DIR"""
import sys, os, re, json, subprocess, urllib.request
sys.path.insert(0, os.path.dirname(__file__))
import common as C
from PIL import Image, ImageDraw

day, work = sys.argv[1], sys.argv[2]
os.makedirs(work, exist_ok=True)
audio = os.path.join(day, 'audio.mp3')
tagsp = os.path.join(day, 'tags.json')
mt = C.mp3_tags(audio)
m = re.search(r'id=([0-9a-f-]{36})', mt.get('comment', ''))
song_id = m.group(1) if m else None
tags = C.load_json(tagsp)
if tags is None:
    title = open(os.path.join(day, 'title.txt')).read().strip() if os.path.exists(os.path.join(day, 'title.txt')) else mt.get('title', 'Untitled')
    url = open(os.path.join(day, 'song_url.txt')).read().strip() if os.path.exists(os.path.join(day, 'song_url.txt')) else (
        f'https://suno.com/song/{song_id}' if song_id else '')
    tags = {'title': title, 'date': C.day_date(day, {}).isoformat(), 'song_url': url,
            'story_tags': [], '_note': 'skeleton generated by prepare.py; add story_tags for NOW SINGING ABOUT boxes'}
    C.save_json(tags, tagsp)
    print('WARNING: no tags.json, wrote skeleton', tagsp)
url = tags.get('song_url', '')
if song_id and url and song_id not in url:
    print(f'WARNING: song_url {url} does not match mp3 id {song_id}')
lines = C.parse_lyrics(open(os.path.join(day, 'lyrics.txt'), encoding='utf-8').read())
C.save_json(lines, os.path.join(work, 'lines.json'))
print(f'{len(lines)} lyric lines in {lines[-1]["sid"] + 1} sections')

# ---- cover art: og:image of the Suno page (cached per URL), else embedded mp3 art, else generated
cover = os.path.join(work, 'cover.jpg'); stamp = os.path.join(work, 'cover_src.txt')
src = None
if url:
    try:
        req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
        html = urllib.request.urlopen(req, timeout=30).read().decode('utf-8', 'ignore')
        m = re.search(r'<meta[^>]+property="og:image"[^>]+content="([^"]+)"', html) or \
            re.search(r'<meta[^>]+content="([^"]+)"[^>]+property="og:image"', html)
        src = m.group(1) if m else None
    except Exception as e:
        print('WARNING: song page fetch failed:', e)
if src and not (os.path.exists(cover) and os.path.exists(stamp) and open(stamp).read().strip() == src):
    req = urllib.request.Request(src, headers={'User-Agent': 'Mozilla/5.0'})
    open(cover + '.dl', 'wb').write(urllib.request.urlopen(req, timeout=60).read())
    Image.open(cover + '.dl').convert('RGB').save(cover, quality=95); os.remove(cover + '.dl')
    open(stamp, 'w').write(src)
elif not src and not os.path.exists(cover):
    r = subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', audio, '-an', '-frames:v', '1', cover])
    if r.returncode != 0 or not os.path.exists(cover):
        im = Image.new('RGB', (1024, 1024), (26, 6, 51)); d = ImageDraw.Draw(im)
        for i in range(0, 1024, 8): d.line([(0, i), (1024, 1024 - i)], fill=(255, 46, 151) if i % 64 == 0 else (60, 20, 110))
        im.save(cover)
    open(stamp, 'w').write('fallback')
im = Image.open(cover)
if im.size[0] != im.size[1]:
    s = min(im.size); l = (im.size[0] - s) // 2; t = (im.size[1] - s) // 2
    im.crop((l, t, l + s, t + s)).save(cover, quality=95)
print('cover:', open(stamp).read().strip(), Image.open(cover).size)
C.save_json({'song_id': song_id, 'duration': C.audio_duration(audio)}, os.path.join(work, 'meta.json'))
